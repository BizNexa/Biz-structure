/**
 * Generates docs/ca-review-pack.md (every record with source and status, golden scenarios) and
 * docs/conflicts-register.md (from rules/conflicts.yaml). Re-run after any rule change.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadRuleSet, hashRuleSet, ROOT } from './lib/load-rules';
import { allRecords } from './lib/lint';
import { sourceLabel } from '../engine/checklist';
import { GOLDEN } from '../tests/fixtures/golden';
import type { RuleSet } from '../rules/schema';

const { ruleset } = loadRuleSet();
if (!ruleset) throw new Error('rule set invalid; run npm run rules:lint');
const rs: RuleSet = ruleset;
const hash = hashRuleSet(rs).slice(0, 12);
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const src = (refs: { doc: string }[]) => esc(refs.map((r) => sourceLabel(r as never)).join('; '));
const period = (r: { effective_from: string; effective_to: string | null }) => `${r.effective_from} → ${r.effective_to ?? 'open'}`;

const counts = allRecords(rs).reduce<Record<string, number>>((m, { rec }) => ((m[rec.verification_status] = (m[rec.verification_status] ?? 0) + 1), m), {});

const L: string[] = [];
L.push('# CA review pack');
L.push('');
L.push(`Rule set **${rs.meta.ruleset_version}** (hash \`${hash}\`), dated ${rs.meta.ruleset_date}. Generated by \`npm run docs:review-pack\`; do not edit by hand.`);
L.push('');
L.push('How to review: for each row, check the statement against the cited page and mark the status column in your copy. Anything not `handbook` or `official` shows as "pending CA verification" in client mode.');
L.push('');
L.push('Status counts: ' + Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(' · '));
L.push('');

L.push('## 1. Evaluation order');
L.push('');
L.push('1. Evaluate every s.22 and s.24 trigger (three-valued: yes / no / unknown).');
L.push('2. Evaluate s.23 exemptions. **Blanket** exemptions (s.23(1)(a), s.23(1)(b), Notification 5/2017-CT) remove the s.22(1) threshold trigger and every trigger marked `displaced`; an overlap with a trigger marked `ca_review` goes to the CA (conflict C-005). **Displacing** exemptions remove only the triggers they list.');
L.push('3. Any trigger still standing → **MANDATORY**.');
L.push('4. Any decisive unknown, contested overlap, or exemption flagged `ca_confirmation_required` → **NEEDS_CA_REVIEW**, with the question to resolve.');
L.push('5. Wants voluntary registration → **VOLUNTARY_ELIGIBLE**. 6. Otherwise **NOT_REQUIRED**.');
L.push('');
L.push('Design decisions for sign-off:');
L.push('- "I don\'t know" on the voluntary-registration preference does not change a NOT_REQUIRED verdict; it adds a note (it is a preference, not a fact).');
L.push('- s.22(1) is tested State by State using all-India turnover against each supply State\'s limit (Illustrations 10-11).');
L.push('- The engine supports as-of dates from 2024-01-01.');
L.push('');

L.push('## 2. Liability rules');
L.push('');
L.push('| Id | Basis | Statement | Effect | Period | Status | Confidence | Source |');
L.push('|---|---|---|---|---|---|---|---|');
for (const r of rs.rules) {
  const eff = r.outcome === 'TRIGGER' ? `trigger (s.23: ${r.s23_override})` : r.outcome === 'EXEMPTION' ? `exemption (${r.scope}${r.displaces?.length ? `: ${r.displaces.join(', ')}` : ''}${r.ca_confirmation_required ? '; CA confirms' : ''})` : 'voluntary';
  L.push(`| ${r.id} | ${esc(r.legal_basis)} | ${esc(r.description)} | ${eff} | ${period(r)} | ${r.verification_status} | ${r.confidence} | ${src(r.source_ref)} |`);
}
L.push('');

L.push('## 3. Thresholds and States');
L.push('');
L.push('| Id | Category | Services/mixed | Goods only | Period | Status | Source |');
L.push('|---|---|---|---|---|---|---|');
for (const t of rs.thresholds) L.push(`| ${t.id} | ${t.threshold_category} | ${t.services_or_mixed_lakh} | ${t.goods_only_lakh} | ${period(t)} | ${t.verification_status} | ${src(t.source_ref)} |`);
L.push('');
const byCat = new Map<string, string[]>();
rs.states.forEach((s) => byCat.set(s.threshold_category, [...(byCat.get(s.threshold_category) ?? []), `${s.name}${s.confidence !== 'certain' ? '*' : ''}`]));
for (const [cat, names] of byCat) L.push(`- **${cat}**: ${names.join(', ')}`);
L.push('');
L.push('\\* not named in the handbook table; placed in the residual row (confidence `likely`).');
L.push('');

L.push('## 4. Deadlines');
L.push('');
L.push('| Id | Statement | Basis | Status | Source |');
L.push('|---|---|---|---|---|');
for (const d of rs.deadlines) L.push(`| ${d.id} | ${esc(d.description)} | ${esc(d.legal_basis)} | ${d.verification_status} | ${src(d.source_ref)} |`);
L.push('');

L.push('## 5. Routes and their conditions');
L.push('');
for (const r of rs.routes) {
  L.push(`### ${r.id}: ${r.name} (${r.form})`);
  L.push('');
  L.push(`${esc(r.description)} Period ${period(r)}. Status **${r.verification_status}**. Source: ${src(r.source_ref)}.`);
  if (r.conditions.length) {
    L.push('');
    L.push('| Condition | Requirement | Status | Source |');
    L.push('|---|---|---|---|');
    r.conditions.forEach((c) => L.push(`| ${c.id} | ${esc(c.description)} | ${c.verification_status} | ${src(c.source_ref)} |`));
  }
  if (r.notes) L.push('', `Note: ${esc(r.notes)}`);
  L.push('');
}

L.push('## 6. Configuration values');
L.push('');
L.push('| Id | Value | Alternatives | Status | Source |');
L.push('|---|---|---|---|---|');
for (const c of rs.config) L.push(`| ${c.id} | ${c.value} ${c.unit} | ${c.alternatives.map((a) => `${a.value} (${esc(a.source)})`).join('; ') || '-'} | ${c.verification_status} | ${src(c.source_ref)} |`);
L.push('');

L.push('## 7. Timelines');
L.push('');
L.push('| Id | Timeline | Period | Status | Source |');
L.push('|---|---|---|---|---|');
for (const t of rs.timelines) L.push(`| ${t.id} | ${esc(t.label)} | ${period(t)} | ${t.verification_status} | ${src(t.source_ref)} |`);
L.push('');

L.push('## 8. Documents');
L.push('');
L.push('| Id | Document | Form versions | Period | Status | Source |');
L.push('|---|---|---|---|---|---|');
for (const d of rs.documents) L.push(`| ${d.id} | ${esc(d.name)} | ${d.form_version_ids.join(', ')} | ${period(d)} | ${d.verification_status} | ${src(d.source_ref)} |`);
L.push('');
L.push('Templates (Circular 257/03/2026-GST): ' + rs.templates.map((t) => `${t.id} - ${t.name} (content ${t.content ? 'present' : '**not verified, left empty**'})`).join('; ') + '.');
L.push('');
L.push('Applicant notes: ' + rs.applicant_notes.map((n) => `${n.id} (${n.verification_status})`).join(', ') + '.');
L.push('');

L.push('## 9. Form versions and lifecycle (out of scope for v1)');
L.push('');
for (const v of rs.form_versions) L.push(`- ${v.id}: ${v.label}, ${period(v)}, ${v.verification_status}`);
L.push('');
for (const l of rs.lifecycle) L.push(`- ${l.id} (${l.topic}): ${esc(l.description)} ${period(l)}, ${l.verification_status}`);
L.push('');

L.push('## 10. Golden scenarios (pending CA sign-off)');
L.push('');
L.push('| Id | Scenario | Expected | Citation | Sign-off |');
L.push('|---|---|---|---|---|');
for (const g of GOLDEN) L.push(`| ${g.id} | ${esc(g.title)} | ${g.expect.verdict}${g.expect.requires ? ` (${g.expect.requires.join(', ')})` : ''} | ${esc(g.citation)} | ${g.signoff} |`);
L.push('');
writeFileSync(join(ROOT, 'docs', 'ca-review-pack.md'), L.join('\n'));

// ---- conflicts register
const C: string[] = [];
C.push('# Conflicts register');
C.push('');
C.push(`Generated from \`rules/conflicts.yaml\` (rule set ${rs.meta.ruleset_version}). The developer has not resolved any of these; each awaits the CA or a primary source.`);
C.push('');
C.push('| Id | Title | Status |');
C.push('|---|---|---|');
rs.conflicts.forEach((c) => C.push(`| ${c.id} | ${esc(c.title)} | ${c.status} |`));
C.push('');
for (const c of rs.conflicts) {
  C.push(`## ${c.id}: ${c.title}`);
  C.push('');
  C.push(esc(c.description));
  C.push('');
  C.push('| Source | Says | Status |');
  C.push('|---|---|---|');
  c.positions.forEach((p) => C.push(`| ${esc(p.source)} | ${esc(p.says)} | ${p.verification_status} |`));
  C.push('');
  C.push(`**How the tool models it:** ${esc(c.how_modelled)}`);
  C.push('');
  C.push(`Related records: ${c.related_ids.join(', ')}. Resolution: ${c.resolution ?? '_open_'}`);
  C.push('');
}
writeFileSync(join(ROOT, 'docs', 'conflicts-register.md'), C.join('\n'));
console.log('✓ wrote docs/ca-review-pack.md and docs/conflicts-register.md');
