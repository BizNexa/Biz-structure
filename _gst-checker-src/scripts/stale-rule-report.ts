/**
 * Stale-rule report: records that need attention as time passes.
 *  - expired (effective_to before today) with no successor of the same kind,
 *  - future-dated (not yet in force),
 *  - secondary/unverified/conflict records older than REVIEW_DAYS since the rule-set date,
 *  - notes containing NOT VERIFIED.
 * Usage: npm run report:stale [-- --today YYYY-MM-DD]
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadRuleSet, ROOT } from './lib/load-rules';
import { allRecords } from './lib/lint';
import { todayISO } from '../engine/ruleset';

const REVIEW_DAYS = 30;
const arg = process.argv.indexOf('--today');
const today = arg > 0 ? process.argv[arg + 1] : todayISO();
const { ruleset: rs } = loadRuleSet();
if (!rs) throw new Error('rule set invalid');
const recs = allRecords(rs);
const days = (a: string, b: string) => Math.round((Date.parse(b) - Date.parse(a)) / 86400000);
const age = days(rs.meta.ruleset_date, today);

const expired = recs.filter(({ rec }) => rec.effective_to && rec.effective_to < today);
const future = recs.filter(({ rec }) => rec.effective_from > today);
const unverifiedOld = age > REVIEW_DAYS ? recs.filter(({ rec }) => !['handbook', 'official'].includes(rec.verification_status)) : [];
const notVerifiedNotes = recs.filter(({ rec }) => /NOT VERIFIED|UNVERIFIED/.test(rec.notes + rec.description));
const openConflicts = rs.conflicts.filter((c) => c.status === 'open');

const sec = (title: string, list: typeof recs, fmt: (r: (typeof recs)[number]) => string) => [`## ${title} (${list.length})`, '', ...(list.length ? list.map(fmt) : ['None.']), ''];
const md = [
  '# Stale-rule report',
  '',
  `As of ${today}. Rule set ${rs.meta.ruleset_version} dated ${rs.meta.ruleset_date} (${age} days old). Generated by \`npm run report:stale\`.`,
  '',
  ...sec('Expired records (historical; kept for date switching)', expired, ({ kind, rec }) => `- ${kind} ${rec.id}: ended ${rec.effective_to}`),
  ...sec('Future-dated records (not yet in force)', future, ({ kind, rec }) => `- ${kind} ${rec.id}: from ${rec.effective_from} (${rec.verification_status})`),
  ...sec(`Unverified records past the ${REVIEW_DAYS}-day review window`, unverifiedOld, ({ kind, rec }) => `- ${kind} ${rec.id}: ${rec.verification_status}`),
  ...sec('Records with NOT VERIFIED / UNVERIFIED in their text', notVerifiedNotes, ({ kind, rec }) => `- ${kind} ${rec.id} (${rec.verification_status})`),
  `## Open conflicts (${openConflicts.length})`,
  '',
  ...openConflicts.map((c) => `- ${c.id} ${c.title}`),
  '',
].join('\n');
writeFileSync(join(ROOT, 'docs', 'stale-rule-report.md'), md);
console.log(`Stale report (${today}): expired ${expired.length}, future ${future.length}, unverified-overdue ${unverifiedOld.length}, NOT VERIFIED ${notVerifiedNotes.length}, open conflicts ${openConflicts.length} → docs/stale-rule-report.md`);
