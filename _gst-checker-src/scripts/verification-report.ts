/** Lists every record (and route condition) that is not `handbook` or `official`. */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadRuleSet, ROOT } from './lib/load-rules';
import { allRecords } from './lib/lint';

const { ruleset: rs } = loadRuleSet();
if (!rs) throw new Error('rule set invalid');
const rows: string[][] = [];
for (const { kind, rec } of allRecords(rs))
  if (rec.verification_status !== 'handbook' && rec.verification_status !== 'official')
    rows.push([rec.verification_status, kind, rec.id, rec.description.replace(/\s+/g, ' ').slice(0, 110)]);
for (const r of rs.routes)
  for (const c of r.conditions)
    if (c.verification_status !== 'handbook' && c.verification_status !== 'official') rows.push([c.verification_status, 'route condition', c.id, c.description.slice(0, 110)]);
const order = ['conflict', 'unverified', 'secondary'];
rows.sort((a, b) => order.indexOf(a[0]) - order.indexOf(b[0]) || a[1].localeCompare(b[1]));

const md = [
  '# Verification report',
  '',
  `Rule set ${rs.meta.ruleset_version}. Records whose status is not \`handbook\` or \`official\`: **${rows.length}**. Generated by \`npm run report:verification\`.`,
  '',
  '| Status | Kind | Id | Statement |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.map((x) => x.replace(/\|/g, '\\|')).join(' | ')} |`),
  '',
].join('\n');
writeFileSync(join(ROOT, 'docs', 'verification-report.md'), md);
const by = rows.reduce<Record<string, number>>((m, r) => ((m[r[0]] = (m[r[0]] ?? 0) + 1), m), {});
console.log(`Not handbook/official: ${rows.length} (${Object.entries(by).map(([k, v]) => `${k} ${v}`).join(', ')}) → docs/verification-report.md`);
