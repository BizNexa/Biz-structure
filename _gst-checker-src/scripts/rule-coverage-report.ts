/**
 * Rule coverage: for every liability rule, is there a test case where it fires and one where it does
 * not (tests/fixtures/rule-cases.ts)? Which rules appear in the golden scenarios' rule chains? Which
 * documents, routes and timelines are reached by at least one golden scenario? Exits 1 if a liability
 * rule lacks either case.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { RULE_CASES } from '../tests/fixtures/rule-cases';
import { GOLDEN } from '../tests/fixtures/golden';
import { run, ruleResult, f } from '../tests/helpers';
import { RULESET } from '../engine/ruleset';
import { ROOT } from './lib/load-rules';

const rows: string[] = [];
let missing = 0;
for (const r of RULESET.rules) {
  const cases = RULE_CASES.filter((c) => c.rule === r.id);
  const fires = cases.filter((c) => c.fires && ruleResult(r.id, f(c.facts), c.asOf) === true).length;
  const not = cases.filter((c) => !c.fires && ruleResult(r.id, f(c.facts), c.asOf) === false).length;
  const golden = GOLDEN.filter((g) => run(g.facts, g.asOf).a.reasons.some((x) => x.rule_id === r.id)).map((g) => g.id);
  if (!fires || !not) missing++;
  rows.push(`| ${r.id} | ${fires} | ${not} | ${golden.join(', ') || '-'} | ${fires && not ? '✓' : '✗'} |`);
}

const reached = { docs: new Set<string>(), routes: new Set<string>() };
for (const g of GOLDEN) {
  const { a, checklist } = run(g.facts, g.asOf);
  checklist.rows.forEach((d) => reached.docs.add(d.id));
  a.recommended_route_ids.forEach((id) => reached.routes.add(id));
}
const unreachedDocs = RULESET.documents.filter((d) => !reached.docs.has(d.id)).map((d) => d.id);
const unreachedRoutes = RULESET.routes.filter((r) => !reached.routes.has(r.id)).map((r) => r.id);

const md = [
  '# Rule coverage report',
  '',
  `Rule set ${RULESET.meta.ruleset_version}. Generated by \`npm run report:coverage\`.`,
  '',
  '| Rule | Firing cases | Non-firing cases | In golden rule chains | OK |',
  '|---|---|---|---|---|',
  ...rows,
  '',
  `Documents not reached by any golden scenario (${unreachedDocs.length}; covered by checklist tests or date tests where noted): ${unreachedDocs.join(', ') || 'none'}`,
  '',
  `Routes not recommended in any golden scenario (${unreachedRoutes.length}): ${unreachedRoutes.join(', ') || 'none'}`,
  '',
].join('\n');
writeFileSync(join(ROOT, 'docs', 'rule-coverage-report.md'), md);
console.log(`Coverage: ${RULESET.rules.length - missing}/${RULESET.rules.length} liability rules have firing and non-firing cases; ${RULESET.documents.length - unreachedDocs.length}/${RULESET.documents.length} documents and ${RULESET.routes.length - unreachedRoutes.length}/${RULESET.routes.length} routes reached by golden scenarios → docs/rule-coverage-report.md`);
if (missing) process.exit(1);
